function selectUser(userName) {
    document.getElementById('user-selection').classList.add('hidden');
    document.getElementById('main-home').classList.remove('hidden');
    document.getElementById('current-user').innerText = userName;
    renderContent();
}

function logout() {
    document.getElementById('main-home').classList.add('hidden');
    document.getElementById('user-selection').classList.remove('hidden');
}

function renderContent() {
    const heroRow = document.getElementById('hero-row');
    const allList = document.getElementById('all-list');

    heroRow.innerHTML = '';
    allList.innerHTML = '';

    const allItems = [...DATA.series, ...DATA.movies];

    // Pick random featured item for hero
    const featured = allItems[Math.floor(Math.random() * allItems.length)];
    setupHero(featured);

    allItems.forEach(item => {
        // Hero cards with hover video
        const heroCard = createHeroCard(item);
        heroRow.appendChild(heroCard);

        // All list cards
        const card = createMovieCard(item);
        allList.appendChild(card);
    });

    // Setup hero play button to play the featured item
    document.getElementById('hero-play-btn').onclick = () => {
        openPlayer(featured);
    };
}

function setupHero(item) {
    const heroVideo = document.getElementById('hero-video');
    const heroTitle = document.getElementById('hero-title');
    const heroDesc = document.getElementById('hero-desc');

    heroVideo.src = item.intro;
    heroVideo.play().catch(() => {});
    heroTitle.textContent = item.name;
    const totalMemories = DATA.series.length + DATA.movies.length;
    heroDesc.textContent = `${totalMemories} memories`;
}

function createHeroCard(item) {
    const div = document.createElement('div');
    div.className = 'hero-card';
    div.style.backgroundImage = `url('${item.thumbnail}')`;

    // Hidden video element for hover preview
    const video = document.createElement('video');
    video.src = item.intro;
    video.muted = true;
    video.loop = true;
    video.playsInline = true;
    video.preload = 'metadata';
    div.appendChild(video);

    // Hover events
    div.addEventListener('mouseenter', () => {
        video.play().catch(() => {});
    });
    div.addEventListener('mouseleave', () => {
        video.pause();
        video.currentTime = 0;
    });

    div.onclick = () => {
        if (item.media.length > 0) {
            openPlayer(item);
        }
    };

    return div;
}

function createMovieCard(item) {
    const div = document.createElement('div');
    div.className = 'movie-card';
    div.style.backgroundImage = `url('${item.thumbnail}')`;
    div.innerHTML = `<span>${item.name}</span>`;

    div.onclick = () => {
        if (item.media.length > 0) {
            openPlayer(item);
        }
    };

    return div;
}

function isVideo(path) {
    return /\.(mp4|mov|MOV|avi|mkv|webm)$/i.test(path);
}

function openPlayer(item) {
    mediaList = item.media;
    currentItem = item;
    currentIndex = 0;
    currentAudioList = item.audio || [];
    currentAudioIndex = 0;

    document.getElementById('player-title').textContent = item.name;
    document.getElementById('media-player').classList.remove('hidden');
    document.body.style.overflow = 'hidden';

    playMedia(currentIndex);
}

function closePlayer() {
    document.getElementById('media-player').classList.add('hidden');
    document.body.style.overflow = 'auto';
    clearTimer();

    const video = document.getElementById('player-video');
    video.pause();
    video.src = '';

    const img = document.getElementById('player-image');
    img.style.display = 'none';
    img.src = '';

    const bgAudio = document.getElementById('bg-audio');
    bgAudio.pause();
    bgAudio.src = '';
    bgAudio.load();
    
    currentAudioList = [];
    currentAudioIndex = 0;
}

function playMedia(index) {
    if (index < 0 || index >= mediaList.length) {
        closePlayer();
        return;
    }

    const img = document.getElementById('player-image');
    const video = document.getElementById('player-video');
    const path = mediaList[index];
    const isFirstItem = (index === 0);

    clearTimer();

    if (isVideo(path)) {
        img.style.display = 'none';
        img.src = '';
        video.style.display = 'block';
        video.src = path;
        // Only first video (intro) has sound; all others muted
        video.muted = !isFirstItem;
        video.play();

        video.onended = () => {
            if (isFirstItem && currentAudioList.length > 0) {
                console.log('Intro ended, starting background audio');
                playNextAudio();
            }
            currentIndex++;
            playMedia(currentIndex);
        };
    } else {
        video.style.display = 'none';
        video.pause();
        video.src = '';
        img.style.display = 'block';

        img.style.animation = 'none';
        img.offsetHeight;
        img.style.animation = 'fadeImage 0.6s ease-in-out';
        img.src = path;

        autoAdvanceTimer = setTimeout(() => {
            currentIndex++;
            playMedia(currentIndex);
        }, IMAGE_DURATION);
    }

    updateProgress();
}

function playNextAudio() {
    const bgAudio = document.getElementById('bg-audio');
    
    if (currentAudioIndex >= currentAudioList.length) {
        currentAudioIndex = 0;
    }
    
    if (currentAudioList.length > 0) {
        bgAudio.src = currentAudioList[currentAudioIndex];
        bgAudio.volume = 0.5;
        bgAudio.load();
        
        bgAudio.play().then(() => {
            console.log(`Playing audio: ${currentAudioList[currentAudioIndex]}`);
        }).catch(err => {
            console.error(`Audio play failed: ${err.message}`);
        });
        
        bgAudio.onended = () => {
            currentAudioIndex++;
            playNextAudio();
        };
        
        bgAudio.onerror = () => {
            console.error(`Failed to load audio: ${currentAudioList[currentAudioIndex]}`);
            currentAudioIndex++;
            if (currentAudioIndex < currentAudioList.length) {
                playNextAudio();
            }
        };
    }
}

function clearTimer() {
    if (autoAdvanceTimer) {
        clearTimeout(autoAdvanceTimer);
        autoAdvanceTimer = null;
    }
}

function updateProgress() {
    const progress = ((currentIndex + 1) / mediaList.length) * 100;
    document.getElementById('player-progress-bar').style.width = `${progress}%`;
}

document.addEventListener('keydown', (e) => {
    if (document.getElementById('media-player').classList.contains('hidden')) return;
    if (e.key === 'Escape') {
        closePlayer();
    }
});

