function initFloatingThumbnails() {
    const container = document.getElementById('floating-bg');
    if (!container) return;
    
    const allThumbnails = [...DATA.series, ...DATA.movies].map(item => item.thumbnail);
    const count = 25;
    
    for (let i = 0; i < count; i++) {
        const thumb = document.createElement('img');
        thumb.className = 'floating-thumb';
        thumb.src = allThumbnails[i % allThumbnails.length];
        
        const size = 80 + Math.random() * 120;
        thumb.style.width = `${size}px`;
        thumb.style.height = `${size * 0.6}px`;
        thumb.style.objectFit = 'cover';
        thumb.style.left = `${Math.random() * 100}%`;
        thumb.style.top = `${Math.random() * 100}%`;
        thumb.style.animationDuration = `${8 + Math.random() * 12}s`;
        thumb.style.animationDelay = `${-Math.random() * 10}s`;
        
        container.appendChild(thumb);
    }
}

